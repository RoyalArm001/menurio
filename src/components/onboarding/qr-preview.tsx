export function QrPreview({ color = "#1d1b18" }: { color?: string }) {
  return (
    <svg
      viewBox="0 0 25 25"
      className="aspect-square w-full"
      role="img"
      aria-label="Preview QR code for Avena restaurant"
    >
      <rect width="25" height="25" rx="2" fill="white" />
      {pattern.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "1" ? (
            <rect key={`${x}-${y}`} x={x + 2} y={y + 2} width="1" height="1" rx="0.15" fill={color} />
          ) : null,
        ),
      )}
    </svg>
  );
}
